"""Запасной слой NLU: регулярки из docs/prototype.html (функция ask()).

Работает, когда модель не уверена (confidence < NLU_MIN_CONFIDENCE) или её не удалось загрузить.
Возвращает (label, 1.0) либо None — «правила тоже не знают», тогда orchestrator спросит уточнение.

Отличие от прототипа: «вклад»/«депозит» в вопросе-определении («вклад это что») — это term,
а не invest_advice (docs/plans/ROLE_B_ai.md, B.3, трудные пары классов).
"""
from __future__ import annotations

import re

from app.ai.parse import normalize, parse_amount

# Форма вопроса-определения: «что такое X», «X это что», «объясни X», «что значит X»
DEFINITION_RE = (
    r"что так|что это|это что|что значит|что за|объясн|расшифру|поясн|определение|"
    r"как работает|как устроен|чем отличает|простыми словами|в чем смысл|что подразумева|"
    r"значение слова|как понять|хочу разобрат|не понимаю что"
)

# Термины: ключи прототипа (TERMS) + то, что спрашивают студенты
TERM_KEYS = (
    "подушк", "кассов", "рассроч", "кредитн", "вклад", "депозит", "инфляц", "кэшбэк", "кешбэк",
    "овердрафт", "ипотек", "накопительн", "страхов", "процентн", "дебетов", "кредитк", "дебетовк",
    "бюджет", "ключев", "сложный процент", "капитализац", "минимальный платеж", "грейс",
    "льготный период", "мошенн", "ставк", "кредит",
)

# Порядок важен: первое совпадение выигрывает (как в ask() прототипа)
RULES: tuple[tuple[str, str], ...] = (
    ("credentials", r"парол|код из|кода из|код подтвержд|смс|sms|cvv|cvc|номер карт|данные карт|"
                    r"пин[- ]?код|\bпин\b|логин и пароль|секретный код|одноразовый код|трехзначный код"),
    ("money_operation", r"перевед[иит]|перевести|\bоплати\b|\bотправь\b|отправить деньги|сделай перевод|"
                        r"проведи (?:оплату|платеж)|сделай платеж|оформи платеж|\bпополни\b|сними налич|"
                        r"\bзакинь\b|\bперекинь\b|\bспиши\b|закрой (?:кредит|долг)|\bзаплати\b|"
                        r"\bкупи\b|\bзакажи\b|вышли деньги"),
    ("invest_advice", r"влож|инвест|акци|облигац|крипт|биткоин|бирж|приумнож|под процент|"
                      r"выгодный вклад|какой вклад|вклад лучше|вклад выгодн|какой депозит|иис\b|"
                      r"куда положить деньги|во что вкладыв|посоветуй.*(?:куп|влож)|золот|доллар"),
    ("deficit_plan", r"что делать|как не уйти|как не уходить|\bплан\b|плана\b|выйти из минус|выкрут|"
                     r"как закрыть|как дожить|как дотянуть|как сэконом|как экономить|сократить трат|"
                     r"урезать|как избежать минус|как убрать минус|надо заработать|где взять деньги|"
                     r"что предпринять|как перестать|как спасти|что мне делать|как жить|"
                     r"варианты|что если денег|не хватает"),
    ("explain", r"почему|как посчит|как считаеш|как считает|откуда|объясни расчет|объясни как|"
                r"из чего|покажи расчет|покажи как|что учтено|на чем основан|как получил|как пришел|"
                r"не понял откуда|не понимаю откуда|покажи формул|разложи|чем ты счита|поясни расчет|"
                r"поясни как|как работает подсчет|как считается"),
    ("categories", r"(?:на что|куда|где).{0,20}(?:трач|уход|утека|слил|денег)|больше всего|"
                   r"по категор|категори|структура расход|топ трат|съедает|состоят.{0,10}расход|"
                   r"состоят.{0,10}трат|статистику расход|распределение трат|сколько (?:я )?трачу|"
                   r"сколько уходит|сколько отдаю|доля трат|самая дорогая|самая жирная"),
    # purchase_check раньше forecast: «хватит ли на наушники за 3000» — это проверка покупки,
    # а «хватит ли до стипендии» (без суммы) — прогноз. Правило с суммой отсеивается ниже.
    ("purchase_check", r"куп|покуп|взять|возьму|позволить|потяну|хватит на|могу ли|смогу ли|"
                       r"присматрива|собираюсь|планиру|стоит ли брать|выдержит"),
    ("forecast", r"хватит|хватает|до стипенд|до стипух|до стип|прогноз|остан|дотяну|дотянуть до|"
                 r"доживу|дожить до|продержус|уйду ли|будет ли минус|минус будет|когда.{0,15}законч|"
                 r"сколько дней до|следующее поступлен|когда.{0,10}стип|что по деньгам|"
                 r"как.{0,10}с деньгами|как.{0,10}с бюджет|че там (?:по|с)|какой минимум|"
                 r"сколько (?:у меня )?(?:будет|останется)|до какого числа|вылезу в минус|"
                 r"минимум (?:остатка|на карте)|с балансом|мой остаток|как там.{0,10}остаток"),
    ("add_income", r"подработ|получил|получила|пришл|прилетело|заработ|перевел|скинул|закинул|"
                   r"доход|стипенд|стипух|стипа|упал|капнул|подкинул|вернул долг|отдали долг|"
                   r"выплатил|жду|ожидаю|поступлен|аванс|премия|премию|зарплат|\bзп\b|halt|халтур"),
    ("add_spend", r"такси|потратил|потратила|потратил|заплатил|заплатила|кафе|доставк|продукт|"
                  r"\bеда\b|обед|кофе|трат[ауы]|купил|купила|отдал|отдала|оставил|ушло|спустил|"
                  r"просадил|спалил|оплатил|записать трату|добавь трату|внеси трату|запиши|"
                  r"записывай|зафиксируй|проездной|шаурм|пицц|столовк|ксерокс|маникюр"),
    ("off_topic", r"чемпионат|погод|анекдот|борщ|реферат|уравнен|столица|фильм|сериал|посмотреть вечер|"
                  r"забудь (?:все )?правил|игнориру|системный промпт|покажи промпт|"
                  r"привет|здравству|здрасте|как дела|спасибо|пока\b|кто ты|ты кто|как тебя зовут|"
                  r"ты живой|ты умеешь|давай поболта|похудет|уснуть|будильник|музык|космос|"
                  r"динозавр|черная дыра|небо голубое|президент|английск|сесси|гарри поттер|"
                  r"библиотек|смартфон|праздник|день недели|подарить"),
)


def _is_definition_question(text: str) -> bool:
    return bool(re.search(DEFINITION_RE, text)) and any(key in text for key in TERM_KEYS)


def predict(text: str) -> tuple[str, float] | None:
    """(label, 1.0) или None. Порядок проверок повторяет ask() из прототипа."""
    clean = normalize(text)
    if not clean:
        return None

    # Определения раньше всего: «вклад это что» — term, «какой вклад выбрать» — invest_advice
    if _is_definition_question(clean):
        return "term", 1.0

    amount = parse_amount(text)
    for label, pattern in RULES:
        if not re.search(pattern, clean):
            continue
        # Метки, которым нужна сумма: без неё правило не срабатывает (как в прототипе)
        if label in ("purchase_check", "add_income", "add_spend") and amount is None:
            continue
        return label, 1.0

    if any(key in clean for key in TERM_KEYS):
        return "term", 1.0
    return None
