def split_cores(cores: list[str], rng: random.Random) -> tuple[list[str], list[str]]:
    cores = sorted(set(cores))
    rng.shuffle(cores)
    n_test = max(4, round(len(cores) * 0.2))
    return cores[n_test:], cores[:n_test]


def generate(cores: list[str], count: int, rng: random.Random, taken: set[str]) -> list[str]:
    """Уникальные (по norm) фразы из ядер; не пересекаются с taken. Ядра берутся по кругу — равномерно."""
    phrases: dict[str, str] = {}
    attempts = 0
    while len(phrases) < count:
        attempts += 1
        if attempts > count * 400:
            raise RuntimeError(f"не хватает разнообразия: {len(phrases)}/{count}")
        core = cores[attempts % len(cores)]
        text = make_phrase(core, rng)
        key = norm(text)
        if len(key) < 2 or key in taken or key in phrases:
            continue
        phrases[key] = text
    return list(phrases.values())


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    assert set(CORES) == set(LABELS) == set(MANUAL), "ядра и ручные фразы должны покрывать ровно 12 меток"
    rng = random.Random(SEED)
    train_rows: list[dict] = []
    test_rows: list[dict] = []
    core_counts: dict[str, tuple[int, int]] = {}
    for label in LABELS:
        train_cores, test_cores = split_cores(CORES[label], rng)
        core_counts[label] = (len(train_cores), len(test_cores))
        manual = sorted(set(MANUAL[label]))
        rng.shuffle(manual)
        manual_test, manual_train = manual[:N_MANUAL_TEST], manual[N_MANUAL_TEST:]
        manual_keys = {norm(t) for t in manual}
        test_texts = manual_test + generate(test_cores, N_TEST - len(manual_test), rng, manual_keys)
        taken = manual_keys | {norm(t) for t in test_texts}
        train_texts = manual_train + generate(train_cores, N_TRAIN - len(manual_train), rng, taken)
        test_rows += [{"text": t, "label": label} for t in test_texts]
        train_rows += [{"text": t, "label": label} for t in train_texts]

    # одна и та же фраза не должна иметь две разные метки (и попадать и в train, и в test)
    seen: dict[str, str] = {}
    for row in train_rows + test_rows:
        key = norm(row["text"])
        assert seen.setdefault(key, row["label"]) == row["label"], f"конфликт меток: {row['text']!r}"
    assert len(seen) == len(train_rows) + len(test_rows), "дубликаты между train и test"

    rng.shuffle(train_rows)
    rng.shuffle(test_rows)
    DATA_DIR.mkdir(exist_ok=True)
    for name, rows in (("intents_train.jsonl", train_rows), ("intents_test.jsonl", test_rows)):
        with open(DATA_DIR / name, "w", encoding="utf-8", newline="\n") as f:
            for row in rows:
                f.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(f"train: {len(train_rows)}  test: {len(test_rows)}")
    train_c = Counter(r["label"] for r in train_rows)
    test_c = Counter(r["label"] for r in test_rows)
    print(f"{'label':<18}{'train':>6}{'test':>6}{'train-ядер':>12}{'test-ядер':>11}")
    for label in LABELS:
        tr, te = core_counts[label]
        print(f"{label:<18}{train_c[label]:>6}{test_c[label]:>6}{tr:>12}{te:>11}")


