def norm(text: str) -> str:
    text = text.lower().replace("ё", "е")
    text = re.sub(r"[^\w\s]", " ", text)
    return re.sub(r"\s+", " ", text).strip()


def render_amount(value: int, rng: random.Random) -> str:
    kinds = ["plain", "plain", "space", "k", "tys", "t", "tr", "word"]
    kind = rng.choice(kinds)
    if kind == "word" and value in WORD_AMOUNTS:
        return WORD_AMOUNTS[value]
    if kind in ("k", "tys", "t", "tr") and value % 1000 == 0:
        n = value // 1000
        return {"k": f"{n}к", "tys": f"{n} тыс", "t": f"{n}т", "tr": f"{n}т.р."}[kind]
    if kind == "space" and value >= 1000:
        return f"{value:,}".replace(",", " ")
    text = str(value)
    if rng.random() < 0.3:
        text += rng.choice([" р", " руб", " рублей", "р", "₽", " ₽"])
    return text


def fill(core: str, rng: random.Random) -> str:
    def sub(match: re.Match) -> str:
        key = match.group(1)
        if key == "amt":
            return render_amount(rng.choice(AMOUNTS), rng)
        if key == "item":
            return rng.choice(ITEMS)
        if key == "date":
            return rng.choice(DATES)
        if key == "past":
            return rng.choice(PAST_DATES)
        if key == "spend":
            return rng.choice(SPEND_THINGS)
        if key == "nom":
            return rng.choice(SPEND_NOM)
        if key == "inc":
            return rng.choice(INCOME_SRC)
        if key == "gave":
            return rng.choice(PEOPLE_GAVE)
        if key == "term":
            return rng.choice(TERMS)
        if key == "code":
            return str(rng.randint(1000, 9999))
        raise KeyError(key)

    return re.sub(r"\{(\w+)\}", sub, core)


def typo(text: str, rng: random.Random) -> str:
    """Одна-две опечатки в словах длиннее 4 букв; цифры и сумму не трогаем."""
    words = text.split(" ")
    candidates = [i for i, w in enumerate(words) if len(w) >= 5 and w.isalpha()]
    for i in rng.sample(candidates, k=min(len(candidates), rng.choice([1, 1, 2]))):
        w = words[i]
        pos = rng.randrange(1, len(w) - 1)
        op = rng.choice(["swap", "drop", "double"])
        if op == "swap":
            w = w[:pos] + w[pos + 1] + w[pos] + w[pos + 2:]
        elif op == "drop":
            w = w[:pos] + w[pos + 1:]
        else:
            w = w[:pos] + w[pos] + w[pos:]
        words[i] = w
    return " ".join(words)


def make_phrase(core: str, rng: random.Random) -> str:
    text = fill(core, rng)
    text = rng.choice(PREFIXES) + text + rng.choice(SUFFIXES)
    if rng.random() < 0.35:
        text += "?"
    if rng.random() < 0.22:
        text = typo(text, rng)
    if rng.random() < 0.2:
        text = text.replace(",", "")
    if rng.random() < 0.2:
        text = text[:1].upper() + text[1:]
    return text.strip()


